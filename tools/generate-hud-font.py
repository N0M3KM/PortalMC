root = Path(__file__).resolve().parents[1]/'src/client/resources/assets/portalmod'
width, height = 128, 60
pixels = bytearray(width*height*4)
chars = [chr(i) for i in range(32,128)]
for index, char in enumerate(chars):
    cx, cy = index % 16 * 8, index // 16 * 10
    for y, row in enumerate(glyphs.get(char.upper(),glyphs['?'])):
        for x, bit in enumerate(row):
            if bit == '1':
                pos = ((cy+y+1)*width+cx+x+1)*4
                pixels[pos:pos+4] = b'\xff\xff\xff\xff'
    # Alpha=1 is visually imperceptible but fixes every glyph's rightmost column/advance.
    pos = ((cy+8)*width+cx+6)*4
    pixels[pos:pos+4] = b'\xff\xff\xff\x01'
def chunk(kind, data):
    return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
raw = b''.join(b'\0'+pixels[y*width*4:(y+1)*width*4] for y in range(height))
png = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,height,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b'')
(root/'textures/font').mkdir(parents=True,exist_ok=True)
(root/'font').mkdir(parents=True,exist_ok=True)
(root/'textures/font/telemetry.png').write_bytes(png)
